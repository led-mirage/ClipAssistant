"""Combine the user/developer guides for export with VS Code Markdown PDF."""

import ast
import html
import os
from pathlib import Path
import re
from urllib.parse import quote, unquote, urlsplit


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "README_ALL.md"
DOCUMENTS = (
    ("README.md", "アプリ概要・使い方"),
    ("README_CONFIG.md", "設定ガイド"),
    ("README_MODELS.md", "対応モデル一覧"),
    ("README_DEV.md", "開発者向けガイド"),
)
HEADING = re.compile(r"^ {0,3}#{1,6}\s+(.+?)(?:\s+#+)?\s*$")
LINK = re.compile(r"(!?\[[^\]\n]*\]\()([^\s)]+)(\))")
IMAGE_SOURCE = re.compile(r'(<img\b[^>]*?\bsrc=)([\"\'])(.*?)(\2)', re.I)


def outside_code_lines(text):
    """Mark fenced code blocks so commands and code examples stay untouched."""
    fence = None
    for line in text.splitlines(keepends=True):
        marker = re.match(r"^ {0,3}(`{3,}|~{3,})", line)
        if fence is not None:
            yield line, False
            if marker and marker[1][0] == fence[0] and len(marker[1]) >= len(fence):
                if not line[marker.end():].strip():
                    fence = None
        elif marker:
            fence = marker[1]
            yield line, False
        else:
            yield line, True


def slug(text):
    text = re.sub(r"<[^>]*>", "", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    text = html.unescape(text).lower().replace("\ufe0f", "")
    return re.sub(r"[^\w\- ]", "", text).replace(" ", "-")


def release_version():
    tree = ast.parse((ROOT / "src/app_const.py").read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "APP_VERSION"
            for target in node.targets
        ):
            return ast.literal_eval(node.value)
    raise ValueError("APP_VERSION was not found")


def build():
    version = release_version()
    sources = {}
    anchors = {}
    heading_ids = {}
    for filename, _ in DOCUMENTS:
        path = ROOT / filename
        text = path.read_text(encoding="utf-8-sig")
        doc_id = "doc-" + path.stem.lower().replace("_", "-")
        sources[path] = text
        anchors[(path, "")] = doc_id
        counts = {}
        headings = []
        for line, outside in outside_code_lines(text):
            match = HEADING.match(line) if outside else None
            if match:
                base = slug(match[1])
                count = counts.get(base, 0)
                counts[base] = count + 1
                fragment = base if count == 0 else f"{base}-{count}"
                anchor = f"{doc_id}-section-{len(headings) + 1}"
                anchors[(path, fragment)] = anchor
                headings.append(anchor)
        heading_ids[path] = iter(headings)

    def destination(target, source, image=False):
        parsed = urlsplit(html.unescape(target))
        if parsed.scheme or parsed.netloc:
            return target
        path = (source.parent / unquote(parsed.path)).resolve() if parsed.path else source
        if not image and path in sources:
            fragment = unquote(parsed.fragment).lower().replace("\ufe0f", "")
            anchor = anchors.get((path, fragment))
            if anchor is None:
                raise ValueError(f"Unresolved document link in {source.name}: {target}")
            return "#" + anchor
        if image:
            if not path.is_file():
                raise FileNotFoundError(f"Image not found: {path}")
            return quote(Path(os.path.relpath(path, OUTPUT.parent)).as_posix(), safe="/")
        # Files outside the combined guides open the matching release on GitHub.
        relative = path.relative_to(ROOT).as_posix()
        url = f"https://github.com/led-mirage/ClipAssistant/blob/v{version}/{quote(relative, safe='/')}"
        return url + ("#" + parsed.fragment if parsed.fragment else "")

    parts = [f"# ClipAssistant AI v{version} 統合ガイド\n\n", "<!-- Generated by tools/build_docs.py; edit the source guides instead. -->\n\n"]
    for filename, label in DOCUMENTS:
        parts.append(f"- [{label}](#{anchors[(ROOT / filename, '')]})\n")
    for filename, _ in DOCUMENTS:
        path = ROOT / filename
        parts.append(f'\n<div style="page-break-before:always"></div>\n\n<a id="{anchors[(path, "")]}"></a>\n\n')
        for line, outside in outside_code_lines(sources[path]):
            if outside:
                if HEADING.match(line):
                    parts.append(f'<a id="{next(heading_ids[path])}"></a>\n\n')
                # Preserve inline code as well as fenced code examples.
                chunks = re.split(r"(`+[^`\n]*`+)", line)
                for index in range(0, len(chunks), 2):
                    chunks[index] = LINK.sub(
                        lambda m: m[1] + destination(m[2], path, image=m[1].startswith("!")) + m[3],
                        chunks[index],
                    )
                    chunks[index] = IMAGE_SOURCE.sub(
                        lambda m: m[1] + m[2] + destination(m[3], path, image=True) + m[4],
                        chunks[index],
                    )
                line = "".join(chunks)
            parts.append(line)
        parts.append("\n")
    # Write only after all links and images have been validated.
    OUTPUT.write_text("".join(parts), encoding="utf-8")
    print(f"Created: {OUTPUT}")


if __name__ == "__main__":
    build()
